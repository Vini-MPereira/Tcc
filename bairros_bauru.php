function normalizar_bairro($texto)
{
    $texto = trim((string)$texto);
    $texto = mb_strtolower($texto, "UTF-8");

    if (function_exists("iconv")) {
        $convertido = @iconv("UTF-8", "ASCII//TRANSLIT//IGNORE", $texto);
        if ($convertido !== false) {
            $texto = $convertido;
        }
    }

    $texto = preg_replace("/[^a-z0-9 ]/i", " ", $texto);
    $texto = preg_replace("/\s+/", " ", $texto);

    return trim($texto);
}

function resolver_bairro($texto, $bairros = null)
{
    global $bairros_bauru;

    if ($bairros === null) {
        $bairros = $bairros_bauru;
    }

    $busca = normalizar_bairro($texto);

    if ($busca === "") {
        return "";
    }

    foreach ($bairros as $bairro) {
        if (normalizar_bairro($bairro["oficial"]) === $busca) {
            return $bairro["oficial"];
        }

        if (normalizar_bairro($bairro["nome"]) === $busca) {
            return $bairro["oficial"];
        }

        foreach ($bairro["busca"] as $termo) {
            if (normalizar_bairro($termo) === $busca) {
                return $bairro["oficial"];
            }
        }
    }

    return "";
}

function procurar_bairros($texto, $bairros = null)
{
    global $bairros_bauru;

    if ($bairros === null) {
        $bairros = $bairros_bauru;
    }

    $busca = normalizar_bairro($texto);

    if ($busca === "") {
        return [];
    }

    $resultados = [];

    foreach ($bairros as $bairro) {
        $encontrou = false;
        $campos = array_merge(
            [$bairro["nome"], $bairro["oficial"]],
            $bairro["busca"]
        );

        foreach ($campos as $campo) {
            if (strpos(normalizar_bairro($campo), $busca) !== false) {
                $encontrou = true;
                break;
            }
        }

        if ($encontrou) {
            $resultados[] = [
                "nome" => $bairro["nome"],
                "oficial" => $bairro["oficial"]
            ];
        }
    }

    usort($resultados, function ($a, $b) use ($busca) {
        $aa = normalizar_bairro($a["nome"]);
        $bb = normalizar_bairro($b["nome"]);

        $a_inicio = strpos($aa, $busca) === 0 ? 0 : 1;
        $b_inicio = strpos($bb, $busca) === 0 ? 0 : 1;

        if ($a_inicio !== $b_inicio) {
            return $a_inicio <=> $b_inicio;
        }

        return strcmp($aa, $bb);
    });

    return array_slice($resultados, 0, 12);
}

function nome_exibicao_bairro($oficial, $bairros = null)
{
    global $bairros_bauru;

    if ($bairros === null) {
        $bairros = $bairros_bauru;
    }

    foreach ($bairros as $bairro) {
        if (normalizar_bairro($bairro["oficial"]) === normalizar_bairro($oficial)) {
            return $bairro["nome"];
        }
    }

    return $oficial;
}
